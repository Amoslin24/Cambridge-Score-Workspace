import assert from 'node:assert/strict';
import {comparisonSessions,summarize} from '../assets/analysis-panels-1125.mjs';
const row=(studentId,status,v,scheme,session='flyers-exact')=>({studentId,status,v,scheme,session});
const group=rows=>comparisonSessions(rows,a=>a.session,a=>{assert.notEqual(a.status,'absent');return a.scheme;});
const a=row('a','recorded',40,'parts'), b=row('b','absent',null,'totals');
const {sessions,unassigned}=group([b,a]);
assert.equal(sessions.size,1);
assert.equal(unassigned.size,0);
assert.deepEqual(summarize([...sessions.values()][0],r=>r.v,60),{n:1,denominator:1,low:1,mean:40,conflicts:0,absent:1});
const many=group([a,b,row('c','recorded',60,'totals')]);
assert.equal(many.sessions.size,2);
assert.ok([...many.sessions.values()].every(r=>r.length===1&&r[0].status==='recorded'));
assert.deepEqual([...many.unassigned.values()],[1,1]);
const none=group([b,row('c','absent',null,'parts')]);
assert.equal(none.sessions.size,1);
assert.equal(none.unassigned.size,0);
assert.equal(summarize([...none.sessions.values()][0],r=>r.v,60).absent,2);
assert.equal(group([a,row('b','absent',null,'totals','other-paper')]).sessions.size,2);
assert.equal(summarize([...group([a,row('a','absent',null,'totals')]).sessions.values()][0],r=>r.v,60).conflicts,1);
console.log('Pass: one scoring structure, ambiguous structure, all absent, exact sitting isolation, duplicates.');
